// generate-promo-catalog.mjs
//
// Builds cloudflare/src/promo-catalog.js — the list of tools the daily promotion
// agent (cloudflare/src/promo.js) posts about: id, English + Tamil name and
// description, page link and picture. Read from the TOOLS / TA_TOOL arrays in
// index.source.html, so it never drifts from the site.
//
// USAGE: node generate-promo-catalog.mjs   (re-run whenever tools are added or renamed)

import fs from 'fs';

const SITE = 'https://pdftoolsindia.com';
const src = fs.readFileSync('index.source.html', 'utf8');

function literal(name, open, close) {
  const start = src.indexOf(`const ${name} = ${open}`);
  if (start < 0) throw new Error(`${name} not found in index.source.html`);
  let i = src.indexOf(open, start), depth = 0, q = null;
  for (; i < src.length; i++) {
    const c = src[i];
    if (q) { if (c === '\\') i++; else if (c === q) q = null; continue; }
    if (c === "'" || c === '"' || c === '`') q = c;
    else if (c === open) depth++;
    else if (c === close && --depth === 0) break;
  }
  return new Function(`return ${src.slice(src.indexOf(open, start), i + 1)}`)(); // our own source file, plain literals
}

const TOOLS = literal('TOOLS', '[', ']');
const TA = literal('TA_TOOL', '{', '}');
const STANDALONE = literal('TOOL_STANDALONE_PAGES', '{', '}');
const slug = (n) => (n === 'Type Race — Typing Practice Game' ? 'typing-race-game' : n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, ''));

const out = TOOLS.map((t) => {
  const page = STANDALONE[t.id] || (fs.existsSync(`tools/${slug(t.name)}.html`) ? `/tools/${slug(t.name)}` : `/?tool=${t.id}`);
  const img = fs.existsSync(`images/tools/${t.id}.jpg`) ? `${SITE}/images/tools/${t.id}.jpg` : '';
  return { id: t.id, cat: t.cat, paid: !!t.cost, color: t.color || '#28407F', icon: t.icon || '🛠', name: t.name.split(' — ')[0], desc: t.desc || '', ta: (TA[t.id] || [])[0] || '', taDesc: (TA[t.id] || [])[1] || '', url: SITE + page, img };
});

fs.writeFileSync('cloudflare/src/promo-catalog.js',
  '// GENERATED by generate-promo-catalog.mjs from index.source.html — do not edit by hand.\n' +
  'export const CATALOG = ' + JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{') + ';\n');
console.log(`promo catalog: ${out.length} tools, ${out.filter((t) => t.img).length} with pictures`);
