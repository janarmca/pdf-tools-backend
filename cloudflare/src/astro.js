const ASTROLOGER_BASE = 'https://astrologer.p.rapidapi.com';
async function astrologerCall(env, path, body) {
  if (!env.ASTROLOGER_API_KEY) throw new Error('Astrology calculation is not configured yet (ASTROLOGER_API_KEY missing on the server).');
  const r = await fetch((env.ASTROLOGER_API_BASE || ASTROLOGER_BASE) + path, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'X-RapidAPI-Key': env.ASTROLOGER_API_KEY,
      'X-RapidAPI-Host': 'astrologer.p.rapidapi.com'
    },
    body: JSON.stringify(body)
  });
  const text = await r.text();
  let data; try { data = JSON.parse(text); } catch { data = { message: text }; }
  if (!r.ok) {
    // FastAPI validation errors (422) come back as {"detail":[{"loc":[...],"msg":"...","type":"..."}]}
    // — surfacing this instead of a generic message tells us EXACTLY which
    // field is wrong, instead of guessing.
    let detailMsg = data.error || data.message;
    if (Array.isArray(data.errors)) {
      detailMsg = data.errors.map(d => `${(d.loc || []).join('.')}: ${d.msg}`).join(' | ');
    } else if (Array.isArray(data.detail)) {
      detailMsg = data.detail.map(d => `${(d.loc || []).join('.')}: ${d.msg}`).join(' | ');
    } else if (typeof data.detail === 'string') {
      detailMsg = data.detail;
    }
    console.error('[astrologerCall] request body was:', JSON.stringify(body));
    console.error('[astrologerCall] error response:', text);
    throw new Error(detailMsg || ('Astrologer API error ' + r.status));
  }
  return data;
}
function toSubject(dateStr, timeStr, coordsStr, name, timezone, city) {
  const [y, m, d] = String(dateStr).split('-').map(Number);
  const [hh, mm] = String(timeStr || '12:00').split(':').map(Number);
  const [lat, lng] = String(coordsStr || '').split(',').map(s => parseFloat(s.trim()));
  return {
    name: name || 'Subject', year: y, month: m, day: d,
    hour: Number.isFinite(hh) ? hh : 12, minute: Number.isFinite(mm) ? mm : 0,
    longitude: lng, latitude: lat,
    city: city || 'Unknown', // required by the API even when explicit coordinates are given
    timezone: timezone || 'Asia/Kolkata', // required by the API — defaults to IST since that's this app's primary audience
    zodiac_type: 'Sidereal', sidereal_mode: 'LAHIRI'
  };
}
// Groups the API's per-planet response (sun.sign, moon.sign, ...) into the
// per-ZODIAC-SIGN shape astrology-plus.html's Rasi chart expects
// (rasi['Aries'] = ['Sun','Mars'] etc.) — the two shapes don't match natively.
const SIGN_NAME_MAP = { Ari:'Aries', Tau:'Taurus', Gem:'Gemini', Can:'Cancer', Leo:'Leo', Vir:'Virgo', Lib:'Libra', Sco:'Scorpio', Sag:'Sagittarius', Cap:'Capricorn', Aqu:'Aquarius', Pis:'Pisces' };
function buildRasiFromSubject(subject) {
  const rasi = {};
  const planetKeys = ['sun','moon','mercury','venus','mars','jupiter','saturn','uranus','neptune','pluto'];
  planetKeys.forEach(pk => {
    const p = subject && subject[pk];
    if (!p || !p.sign) return;
    const signName = SIGN_NAME_MAP[p.sign] || p.sign;
    if (!rasi[signName]) rasi[signName] = [];
    rasi[signName].push(pk.charAt(0).toUpperCase() + pk.slice(1) + (p.retrograde ? ' (R)' : ''));
  });
  return rasi;
}
